-- Little Learners V124: quiz results. One result per student, per quiz, per month:
-- a newer attempt in the same month replaces the previous one (total and per-question detail).

create table public.quiz_results (
  id               bigint generated by default as identity primary key,
  teacher_id       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  student_id       bigint not null references public.students(id) on delete cascade,
  quiz_id          text not null references public.quizzes(id) on delete cascade,
  month            date not null check (extract(day from month) = 1),
  score            integer not null check (score >= 0),
  total            integer not null check (total >= 0 and score <= total),
  started_at       timestamptz,
  finished_at      timestamptz not null,
  duration_seconds integer check (duration_seconds >= 0),
  updated_at       timestamptz not null default now(),
  unique (student_id, quiz_id, month)
);

create table public.quiz_result_answers (
  result_id          bigint not null references public.quiz_results(id) on delete cascade,
  teacher_id         uuid not null default auth.uid() references auth.users(id) on delete cascade,
  position           integer not null,
  question_id        text not null,
  prompt             text not null default '',
  chosen_option_ids  text[] not null default '{}',
  chosen_text        text not null default '',
  correct            boolean not null,
  response_ms        integer,
  primary key (result_id, position)
);

create index quiz_results_quiz_month on public.quiz_results (quiz_id, month);
create index quiz_results_teacher    on public.quiz_results (teacher_id);
create index quiz_results_student    on public.quiz_results (student_id);
create index quiz_result_answers_teacher on public.quiz_result_answers (teacher_id);

alter table public.quiz_results        enable row level security;
alter table public.quiz_result_answers enable row level security;

-- Teachers only see and write results of their own students and quizzes.
create policy quiz_results_own_select on public.quiz_results for select to authenticated using ((select auth.uid()) = teacher_id);
create policy quiz_results_own_insert on public.quiz_results for insert to authenticated with check (
  (select auth.uid()) = teacher_id
  and exists (select 1 from public.students s where s.id = student_id and s.teacher_id = (select auth.uid()))
  and exists (select 1 from public.quizzes q where q.id = quiz_id and q.teacher_id = (select auth.uid())));
create policy quiz_results_own_update on public.quiz_results for update to authenticated using ((select auth.uid()) = teacher_id) with check ((select auth.uid()) = teacher_id);
create policy quiz_results_own_delete on public.quiz_results for delete to authenticated using ((select auth.uid()) = teacher_id);

create policy quiz_result_answers_own_select on public.quiz_result_answers for select to authenticated using ((select auth.uid()) = teacher_id);
create policy quiz_result_answers_own_insert on public.quiz_result_answers for insert to authenticated with check ((select auth.uid()) = teacher_id);
create policy quiz_result_answers_own_update on public.quiz_result_answers for update to authenticated using ((select auth.uid()) = teacher_id) with check ((select auth.uid()) = teacher_id);
create policy quiz_result_answers_own_delete on public.quiz_result_answers for delete to authenticated using ((select auth.uid()) = teacher_id);

revoke all on public.quiz_results, public.quiz_result_answers from anon;
grant select, insert, update, delete on public.quiz_results, public.quiz_result_answers to authenticated;

-- Save one finished quiz. Keeps only the latest attempt of each month: an older
-- attempt arriving late (e.g. from an offline tablet) never replaces a newer one.
create or replace function public.save_quiz_result(p_result jsonb, p_answers jsonb)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_finished timestamptz := (p_result->>'finished_at')::timestamptz;
  v_month    date := date_trunc('month', (p_result->>'month')::date)::date;
  v_id       bigint;
  v_existing timestamptz;
begin
  select id, finished_at into v_id, v_existing from public.quiz_results
   where student_id = (p_result->>'student_id')::bigint and quiz_id = p_result->>'quiz_id' and month = v_month;

  if v_id is not null and v_existing >= v_finished then
    return; -- a newer result for this month is already saved
  end if;

  if v_id is null then
    insert into public.quiz_results (student_id, quiz_id, month, score, total, started_at, finished_at, duration_seconds)
    values ((p_result->>'student_id')::bigint, p_result->>'quiz_id', v_month, (p_result->>'score')::int, (p_result->>'total')::int,
            (p_result->>'started_at')::timestamptz, v_finished, (p_result->>'duration_seconds')::int)
    returning id into v_id;
  else
    update public.quiz_results set score = (p_result->>'score')::int, total = (p_result->>'total')::int,
      started_at = (p_result->>'started_at')::timestamptz, finished_at = v_finished,
      duration_seconds = (p_result->>'duration_seconds')::int, updated_at = now()
    where id = v_id;
    delete from public.quiz_result_answers where result_id = v_id;
  end if;

  insert into public.quiz_result_answers (result_id, position, question_id, prompt, chosen_option_ids, chosen_text, correct, response_ms)
  select v_id, x.position, x.question_id, left(coalesce(x.prompt, ''), 300), coalesce(x.chosen_option_ids, '{}'), left(coalesce(x.chosen_text, ''), 200), x.correct, x.response_ms
  from jsonb_to_recordset(coalesce(p_answers, '[]'::jsonb)) as x(position int, question_id text, prompt text, chosen_option_ids text[], chosen_text text, correct boolean, response_ms int);
end $$;

revoke execute on function public.save_quiz_result(jsonb, jsonb) from anon, public;
grant execute on function public.save_quiz_result(jsonb, jsonb) to authenticated;
