-- Little Learners Activities gets its own class list, separate from Little Learners (letters app).
-- Before: both apps used public.students, and quiz_results.student_id pointed to it (ON DELETE
-- CASCADE), so deleting a child in Little Learners also erased that child's activity results.
-- After: Activities uses public.activities_students; public.students belongs to Little Learners only.
-- The current children are copied with the SAME ids, so every existing result stays linked.
-- New Activities students start at id 1001 so the two lists never get mixed up.
-- Nothing in public.students / assessments / letter_results is changed.
-- Backup of every table taken before this change: schema backup_20261030.

create table public.activities_students (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 60),
  active      boolean default true,
  created_at  timestamptz default now(),
  teacher_id  uuid default auth.uid() references auth.users(id),
  animal      text,
  avatar_path text,
  sort_order  integer,
  updated_at  timestamptz not null default now()
);

insert into public.activities_students (id, name, active, created_at, teacher_id, animal, avatar_path, sort_order, updated_at)
  overriding system value
  select id, name, active, created_at, teacher_id, animal, avatar_path, sort_order, updated_at from public.students;

select setval(pg_get_serial_sequence('public.activities_students', 'id'),
              greatest(1000, (select coalesce(max(id), 0) from public.activities_students)));

create index activities_students_teacher on public.activities_students (teacher_id);
create trigger activities_students_touch before update on public.activities_students
  for each row execute function public.ll_touch_updated_at();

alter table public.activities_students enable row level security;
revoke all on public.activities_students from anon;
grant select, insert, update, delete on public.activities_students to authenticated;
create policy activities_students_own on public.activities_students for all to authenticated
  using (teacher_id = (select auth.uid())) with check (teacher_id = (select auth.uid()));

-- Results now belong to the Activities class list.
alter table public.quiz_results drop constraint quiz_results_student_id_fkey;
alter table public.quiz_results add constraint quiz_results_student_id_fkey
  foreign key (student_id) references public.activities_students(id) on delete cascade;

drop policy quiz_results_own_insert on public.quiz_results;
create policy quiz_results_own_insert on public.quiz_results for insert to authenticated
  with check (
    (select auth.uid()) = teacher_id
    and exists (select 1 from public.activities_students s where s.id = student_id and s.teacher_id = (select auth.uid()))
    and exists (select 1 from public.quizzes q where q.id = quiz_id and q.teacher_id = (select auth.uid()))
  );
